def s_bulk():
    section("bulk-body robustness")
    u = mk_user("bk")
    r = post_exp(u, 1, note="x" * 200000)
    check("200 KB note -> 201 or 413/422, not 5xx", r.status in (201, 413, 422), r.status)
    try:
        r = call("POST", "/expenses", raw='{"amount": 1, "date": "2026-10-03", "category": "x", "pad": "' + "y" * 1000000 + '"}', token=u.token)
        check("1 MB extra field -> not 5xx", r.status < 500, r.status)
    except ConnectionError:
        # the server answers 413 from the headers and hangs up while the client is still sending
        check("1 MB extra field -> refused early (connection closed after 413)", True)
    r = call("GET", "/expenses?category=" + "a" * 20000, token=u.token)
    check("20 KB query string -> not 5xx", r.status < 500, r.status)
    r = call("GET", "/expenses", headers={"X-Junk": "j" * 8000}, token=u.token)
    check("8 KB custom header -> not 5xx", r.status < 500, r.status)


