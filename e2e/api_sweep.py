def s_sessions():
    section("sessions")
    u = mk_user("s")
    t1 = u.token
    r2 = call("POST", "/auth/login", {"username": u.name, "password": PW})
    t2 = r2.j["token"]
    check("second login gives a different token", t1 != t2)
    check("both tokens work", call("GET", "/auth/me", token=t1).status == 200 and call("GET", "/auth/me", token=t2).status == 200)
    r = call("POST", "/auth/logout", token=t1)
    check("logout -> 204 with empty body", r.status == 204 and r.body == b"", dd(r))
    check("logged-out token is dead on /auth/me", call("GET", "/auth/me", token=t1).status == 401)
    check("logged-out token is dead on data endpoints", call("GET", "/expenses", token=t1).status == 401 and call("GET", "/account", token=t1).status == 401)
    check("other session of the same user still works after logout", call("GET", "/auth/me", token=t2).status == 200)
    r = call("POST", "/auth/logout", token=t1)
    check("logging out twice -> 401 the second time", r.status == 401, dd(r))
    r = call("POST", "/auth/register", {"username": uname("q"), "password": PW})
    other = r.j["token"]
    check("another user's session is unaffected by logout", call("GET", "/auth/me", token=other).status == 200)
    check("user can log in again after logging out", call("POST", "/auth/login", {"username": u.name, "password": PW}).status == 200)
    check("logout of t2", call("POST", "/auth/logout", token=t2).status == 204 and call("GET", "/auth/me", token=t2).status == 401)

    if DB_PATH:
        v = mk_user("e")
        t_old = v.token
        t_new = call("POST", "/auth/login", {"username": v.name, "password": PW}).j["token"]
        t_edge = call("POST", "/auth/login", {"username": v.name, "password": PW}).j["token"]

        def setage(tok, **delta):
            ts = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(**delta)).strftime("%Y-%m-%d %H:%M:%S")
            conn = sqlite3.connect(DB_PATH, timeout=15)
            try:
                conn.execute("UPDATE sessions SET created = ? WHERE token_hash=?", (ts, hashlib.sha256(tok.encode()).hexdigest()))
                conn.commit()
            finally:
                conn.close()

        setage(t_old, days=31)
        setage(t_edge, days=29, hours=23)
        check("session older than 30 days (31d) -> 401", call("GET", "/auth/me", token=t_old).status == 401)
        check("... on data endpoints too", call("GET", "/account", token=t_old).status == 401)
        check("session 29d23h old is still valid", call("GET", "/auth/me", token=t_edge).status == 200)
        check("fresh session of same user unaffected", call("GET", "/auth/me", token=t_new).status == 200)
        setage(t_edge, days=30, minutes=1)
        check("session 30d+1min old -> 401", call("GET", "/auth/me", token=t_edge).status == 401)
        check("user with expired sessions can log in again", call("POST", "/auth/login", {"username": v.name, "password": PW}).status == 200)
        check("logout with an expired token -> 401", call("POST", "/auth/logout", token=t_old).status == 401)
    else:
        info("session-expiry checks skipped (no --db / SESSION_DB: only possible against the local server)")


