class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


_OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}), _NoRedirect)
NO = object()  # "no JSON body"
FIVE_XX, ERR_SHAPE, TRACES, EDGE = [], [], [], []


class Resp:
    def __init__(self, status, headers, body, ms):
        self.status, self.headers, self.body, self.ms = status, headers, body, ms
        self._j = NO
        self.edge = False  # error page generated by the hosting edge/proxy (WAF, nginx), not by the app

    @property
    def text(self):
        return self.body.decode("utf-8", "replace")

    @property
    def j(self):
        if self._j is NO:
            try:
                self._j = json.loads(self.body)
            except Exception:
                self._j = None
        return self._j

    def h(self, name):
        return self.headers.get(name)

    def __repr__(self):
        return f"<{self.status} {self.text[:160]!r}>"


def call(method, path, body=NO, token=None, auth=NO, raw=None, headers=None, timeout=90):
    h = dict(headers or {})
    data = None
    if raw is not None:
        data = raw if isinstance(raw, bytes) else raw.encode()
        h.setdefault("Content-Type", "application/json")
    elif body is not NO:
        data = json.dumps(body).encode()
        h["Content-Type"] = "application/json"
    if auth is not NO:
        if auth is not None:
            h["Authorization"] = auth
    elif token:
        h["Authorization"] = "Bearer " + token
    req = urllib.request.Request(BASE + path, data=data, method=method, headers=h)
    t0 = time.perf_counter()
    try:
        with _OPENER.open(req, timeout=timeout) as r:
            resp = Resp(r.status, r.headers, r.read(), (time.perf_counter() - t0) * 1000)
    except urllib.error.HTTPError as e:
        resp = Resp(e.code, e.headers, e.read(), (time.perf_counter() - t0) * 1000)
    except (urllib.error.URLError, OSError, http.client.HTTPException) as e:  # connection-level rejection
        resp = Resp(0, {}, repr(e).encode(), (time.perf_counter() - t0) * 1000)
    desc = f"{method} {path[:80]}"
    if (not IS_LOCAL) and resp.status in (400, 403, 413, 414, 431) and "html" in (resp.h("content-type") or ""):
        resp.edge = True
        EDGE.append(f"{desc} -> {resp.status}")
    low = resp.body[:4000].lower()
    if b"traceback (most recent" in low or b'file "' in low:
        TRACES.append(desc)
    if resp.status >= 500:
        FIVE_XX.append(f"{desc} -> {resp.status}")
    elif resp.status >= 400 and method != "HEAD" and not resp.edge:
        ok = (resp.h("content-type") or "").startswith("application/json") and isinstance(resp.j, dict) \
            and "detail" in resp.j
        if not ok:
            ERR_SHAPE.append(f"{desc} -> {resp.status} {resp.text[:60]!r}")
    return resp


