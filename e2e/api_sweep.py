def parallel(n, fn):
    barrier = threading.Barrier(n)
    out = [None] * n

    def w(i):
        try:
            barrier.wait(timeout=60)
            out[i] = fn(i)
        except Exception as e:  # noqa: BLE001
            out[i] = e

    ts = [threading.Thread(target=w, args=(i,)) for i in range(n)]
    [t.start() for t in ts]
    [t.join() for t in ts]
    return out


def wake():
    deadline = time.time() + 180
    last = None
    while time.time() < deadline:
        try:
            r = call("GET", "/", timeout=40)
            if r.status < 500:
                return r
            last = r
        except Exception as e:  # noqa: BLE001
            last = e
        time.sleep(4)
    raise SystemExit(f"server at {BASE} did not wake up: {last}")


