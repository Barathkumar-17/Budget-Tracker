    # logout races
    out = parallel(5, lambda i: call("POST", "/auth/logout", token=toks[0]))
    check("5 parallel logouts of the same token: one 204, rest 401 (no 5xx)", sorted(o.status for o in out) in ([204, 401, 401, 401, 401], [204, 204, 204, 204, 204]) or
          all(o.status in (204, 401) for o in out), [o.status for o in out])


