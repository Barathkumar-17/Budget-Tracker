def D(x):
    return Decimal(repr(x)) if isinstance(x, float) else Decimal(x)


def money_eq(x, expected):
    """x (a JSON number) equals expected (str/Decimal/int) exactly, in decimal arithmetic."""
    return isinstance(x, (int, float)) and not isinstance(x, bool) and D(x) == Decimal(str(expected))


