def s_auth_headers():
    section("auth: Authorization header handling")
    u = mk_user("a")
    out = mk_user("o")
    api(out, "POST", "/auth/logout")
    variants = {
        "no header": None, "empty header": "", "'Bearer' alone": "Bearer", "'Bearer ' empty token": "Bearer ",
        "garbage token": "Bearer garbage", "no scheme": "garbage", "Basic scheme": "Basic dXNlcjpwYXNz",
        "Token scheme": "Token abcdef", "jwt-looking expired": "Bearer eyJhbGciOiJIUzI1NiJ9.eyJleHAiOjF9.c2ln",
        "10k-char token": "Bearer " + "A" * 10000, "non-ascii token": "Bearer \xff\xfe\xe9",
        "quoted token": 'Bearer "abc"', "logged-out session token": "Bearer " + out.token,
        "valid token without scheme": u.token, "valid token + 'x'": "Bearer " + u.token + "x",
        "valid token truncated": "Bearer " + u.token[:-1], "valid token + extra word": f"Bearer {u.token} extra",
        "two tokens": f"Bearer {u.token}, Bearer {u.token}",
    }
    for label, hv in variants.items():
        bad = []
        for m, p, b in ENDPOINTS:
            r = call(m, p, b, auth=hv)
            if r.status == 0 and not IS_LOCAL and "non-ascii" in label:
                continue  # the hosting edge drops connections carrying non-ASCII header bytes
            if not (r.status == 401 and r.j == {"detail": "Please log in again"}
                    and (r.h("www-authenticate") or "").lower() == "bearer"):
                bad.append((m, p, r.status))
        check(f"401 + exact body + WWW-Authenticate on all {len(ENDPOINTS)} endpoints: {label}", not bad, bad[:4])
    # 401 wins over validation errors (does not leak validation details to anonymous callers)
    r = call("POST", "/expenses", {"amount": -1}, auth=None)
    check("anonymous + invalid body -> 401 (not 422)", r.status == 401, dd(r))
    r = call("GET", "/dashboard?month=bad", auth=None)
    check("anonymous + invalid month -> 401 (not 422)", r.status == 401, dd(r))
    r = call("DELETE", "/expenses/abc", auth=None)
    check("anonymous + non-int path id -> 401 (not 422)", r.status == 401, dd(r))

    for label, hv, want in [
        ("lowercase 'bearer'", "bearer " + u.token, 200), ("uppercase 'BEARER'", "BEARER " + u.token, 200),
        ("mixed 'bEaReR'", "bEaReR " + u.token, 200), ("exact", "Bearer " + u.token, 200),
        ("trailing space", "Bearer " + u.token + " ", 200),
    ]:
        r = call("GET", "/auth/me", auth=hv)
        check(f"valid token with {label} -> {want}", r.status == want, dd(r))
    for label, hv in [("two spaces", "Bearer  " + u.token), ("tab separator", "Bearer\t" + u.token)]:
        r = call("GET", "/auth/me", auth=hv)
        check(f"valid token with {label} between scheme and token -> 200 or 401, never 5xx",
              r.status in (200, 401), dd(r))
        info(f"Bearer + {label} + valid token -> {r.status}")
    r = call("GET", "/auth/me", token=u.token)
    check("auth/me shape", r.status == 200 and r.j == {"username": u.name}, dd(r))


